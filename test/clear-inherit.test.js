'use strict';
// /clear 뒤 새 세션이 그룹 자리를 이어받는지: 같은 프로세스의 세션 ID 교체 + /clear 기록, 창이 못 본 경우의 시간 판정,
// /resume(/clear 기록 없음)과 시간 차가 큰 경우는 이어받지 않음. 이어받는 것: 자리·역할·대장·사용자가 붙인 이름, 옛 세션은 보관함으로.
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');
const { spawn } = require('child_process');
const fx = require('./helpers/fixture');

const { home, project, markers } = fx.makeHome();
const { rec } = fx;
const stub = require('./helpers/vscode-stub').install({
  extDir: path.join(__dirname, '..'), language: 'en', workspace: project,
  config: { attentionMarkerDir: markers, pollSeconds: 2, notifyStuckMinutes: 0, notifyWaiting: false },
});
const ext = require('../extension.js');

const now = Date.now();
const MIN = 60000;
const iso = (t) => new Date(t).toISOString();
const S = {
  old1: 'c1ea0000-0001-4000-8000-000000000001', new1: 'c1ea0000-0001-4000-8000-0000000000a1',
  old2: 'c1ea0000-0002-4000-8000-000000000002', new2: 'c1ea0000-0002-4000-8000-0000000000a2',
  old3: 'c1ea0000-0003-4000-8000-000000000003', new3: 'c1ea0000-0003-4000-8000-0000000000a3',
  old4: 'c1ea0000-0004-4000-8000-000000000004', res4: 'c1ea0000-0004-4000-8000-0000000000b4',
};
// Claude Code가 /clear 뒤 새 기록 맨 앞에 남기는 줄들(안내문 + /clear 명령 + 빈 출력)
const clearHead = (ts) => [
  { type: 'user', isMeta: true, message: { role: 'user', content: '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>' }, cwd: project, timestamp: iso(ts) },
  { type: 'user', message: { role: 'user', content: '<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>' }, cwd: project, timestamp: iso(ts + 5) },
  { type: 'user', message: { role: 'user', content: '<local-command-stdout></local-command-stdout>' }, cwd: project, timestamp: iso(ts + 10) },
];
const setMtime = (sid, t) => { const f = path.join(home, '.claude', 'projects', fx.encode(project), sid + '.jsonl'); fs.utimesSync(f, new Date(t), new Date(t)); };

// 옛 세션들(그룹 "Team" 안): old1 대장·시험(이름 "Wing-2", 실행 중), old2 디자인(끝남), old3 기획(끝남), old4 검토(실행 중)
fx.claudeSession(home, project, S.old1, [rec.user(project, now - 30 * MIN, 'Test the flow'), rec.aiTitle(S.old1, 'Flow tester'), rec.customTitle(S.old1, 'Wing-2')]);
fx.claudeSession(home, project, S.old2, [rec.user(project, now - 20 * MIN, 'Design the page'), rec.customTitle(S.old2, 'Wing-4')]);
fx.claudeSession(home, project, S.old3, [rec.user(project, now - 40 * MIN, 'Plan it'), rec.aiTitle(S.old3, 'Planner')]);
fx.claudeSession(home, project, S.old4, [rec.user(project, now - 25 * MIN, 'Review it'), rec.aiTitle(S.old4, 'Reviewer')]);
// 창이 못 본 /clear: old2가 끝난 0.2초 뒤 new2가 /clear로 시작(다른 프로세스로 실행 중)
const t2 = now - 3 * MIN;
fx.claudeSession(home, project, S.new2, [...clearHead(t2 + 200), rec.user(project, t2 + 5000, 'Continue the design'), rec.aiTitle(S.new2, 'Some AI title 2')]);
setMtime(S.old2, t2);
// 시간 차가 큰 /clear: old3가 끝나고 5분 뒤 시작 → 이어받지 않는다
const t3 = now - 20 * MIN;
fx.claudeSession(home, project, S.new3, [...clearHead(t3 + 5 * MIN), rec.user(project, t3 + 5 * MIN + 2000, 'Something else'), rec.aiTitle(S.new3, 'Unrelated')]);
setMtime(S.old3, t3);
// /resume 대상(옛 세션, /clear 기록 없음)
fx.claudeSession(home, project, S.res4, [rec.user(project, now - 60 * MIN, 'An older task'), rec.aiTitle(S.res4, 'Older task')]);

const sleepers = [spawn('sleep', ['120'], { stdio: 'ignore' }), spawn('sleep', ['120'], { stdio: 'ignore' }), spawn('sleep', ['120'], { stdio: 'ignore' })];
const [pA, pB, pC] = sleepers.map((x) => x.pid);
fx.registerSession(home, pA, S.old1, { status: 'idle', cwd: project, name: 'a', nameSource: 'derived' });
fx.registerSession(home, pB, S.old4, { status: 'idle', cwd: project, name: 'b', nameSource: 'derived' });
fx.registerSession(home, pC, S.new2, { status: 'idle', cwd: project, name: 'c', nameSource: 'derived' });

const groupsFile = () => path.join(stub.context.globalStorageUri.fsPath, 'session-groups.json');
const archiveFile = () => path.join(stub.context.globalStorageUri.fsPath, 'archived-sessions.json');
fs.mkdirSync(path.dirname(groupsFile()), { recursive: true });
fs.writeFileSync(groupsFile(), JSON.stringify({ groups: [{ id: 'g1', name: 'Team', memo: '', lead: S.old1, at: now, members: {
  [S.old1]: { role: 'test', at: now }, [S.old2]: { role: 'design', at: now }, [S.old3]: { role: 'plan', at: now }, [S.old4]: { role: 'review', at: now },
} }] }));
const groups = () => JSON.parse(fs.readFileSync(groupsFile(), 'utf8')).groups[0];
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function waitFor(fn, what, ms = 15000) {
  const end = Date.now() + ms;
  for (;;) { const v = fn(); if (v) return v; if (Date.now() > end) throw new Error('기다리다 시간 초과: ' + what); await sleep(50); }
}
let web;
const P = () => web.lastPayload();
const team = () => (P().teams || []).find((t) => t.name === 'Team');

test.before(async () => {
  ext.activate(stub.context);
  web = stub.openWebview('claudeSessionChanges.sessions');
  web.send({ type: 'ready' });
  await waitFor(() => P() && team(), '그룹 Team');
});
test.after(async () => { for (const s of sleepers) s.kill(); await ext.deactivate(); });

test('창이 못 본 /clear: 같은 폴더에서 옛 기록이 끝난 몇 초 안에 /clear로 시작한 새 세션이 자리·역할·이름을 이어받는다', async () => {
  const g = await waitFor(() => { const x = groups(); return x.members[S.new2] && x; }, 'new2가 그룹에');
  assert.deepStrictEqual([g.members[S.new2].role, g.members[S.new2].name], ['design', 'Wing-4']);
  assert.ok(!g.members[S.old2], '옛 세션은 그룹에서 빠진다');
  assert.ok(JSON.parse(fs.readFileSync(archiveFile(), 'utf8')).archived[S.old2], '옛 세션은 보관함으로');
  // 새 세션 제목이 AI 제목이어도 그룹에 남긴 옛 이름으로 보인다(보드 표의 이름과 짝이 맞게)
  await waitFor(() => team() && team().rows.some((r) => r.sid === S.new2 && r.title === 'Wing-4'), '새 세션이 옛 이름으로');
});

test('시간 차가 큰 /clear 세션과 /clear 기록이 없는 세션은 이어받지 않는다', () => {
  const g = groups();
  assert.ok(g.members[S.old3] && !g.members[S.new3], '5분 뒤 /clear는 다른 일로 본다');
});

test('같은 프로세스가 /clear로 세션 ID를 바꾸면 자리·역할·대장·이름을 이어받고, /resume으로 바꾼 것은 그대로 둔다', async () => {
  // 첫 읽기에서 pA → old1, pB → old4를 기억한 뒤 바꾼다
  await waitFor(() => (stub.context.globalState.get('claudeSessionChanges.procSids') || {}) && Object.values(stub.context.globalState.get('claudeSessionChanges.procSids') || {}).includes(S.old1), '프로세스 기억');
  const t1 = Date.now();
  setMtime(S.old1, t1 - 5 * MIN); // 시간 판정으로는 짝이 안 되게(같은 프로세스 판정만 시험)
  fx.claudeSession(home, project, S.new1, [...clearHead(t1), rec.user(project, t1 + 1000, 'Next test round'), rec.aiTitle(S.new1, 'Some AI title 1')]);
  fx.registerSession(home, pA, S.new1, { status: 'busy', cwd: project, name: 'a', nameSource: 'derived' });
  fx.registerSession(home, pB, S.res4, { status: 'idle', cwd: project, name: 'b', nameSource: 'derived' }); // /resume: 기록에 /clear 없음
  await stub.commands.get('claudeSessionChanges.refresh')();
  const g = await waitFor(() => { const x = groups(); return x.members[S.new1] && x; }, 'new1이 그룹에');
  assert.deepStrictEqual([g.members[S.new1].role, g.members[S.new1].name, g.lead], ['test', 'Wing-2', S.new1], '역할·이름·대장을 이어받는다');
  assert.ok(!g.members[S.old1]);
  assert.ok(g.members[S.old4] && !g.members[S.res4], '/resume으로 다른 세션을 연 것은 이어받지 않는다');
  await waitFor(() => team() && team().rows.some((r) => r.sid === S.new1 && r.title === 'Wing-2' && r.lead), '새 세션이 대장·옛 이름으로');
  // 사용자가 새 세션을 그룹에서 빼면 다시 넣지 않는다(한 번 이은 짝은 기억)
  await stub.commands.get('claudeSessionChanges.removeFromGroup')(S.new1);
  await stub.commands.get('claudeSessionChanges.refresh')();
  await sleep(2500);
  assert.ok(!groups().members[S.new1], '뺀 세션을 다시 넣지 않는다');
});
